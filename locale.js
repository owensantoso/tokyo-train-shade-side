export function resolveLanguage({ urlLanguage, savedLanguage, browserLanguages = [] } = {}) {
  if (SUPPORTED.has(urlLanguage)) return urlLanguage;
  if (SUPPORTED.has(savedLanguage)) return savedLanguage;
  return browserLanguages.some((language) => language?.toLowerCase().startsWith("ja")) ? "ja" : "en";
}

export function translate(language, key, values = {}) {
  const template = MESSAGES[language]?.[key] ?? MESSAGES.en[key] ?? key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}
